  date date NOT NULL,
  state text NOT NULL,
  district text NOT NULL,
  population integer NOT NULL,
  CONSTRAINT district_population_pkey PRIMARY KEY (date, state, district)
);

ALTER TABLE public.district_population ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "authenticated_select" ON public.district_population;
CREATE POLICY "authenticated_select"
  ON public.district_population
  FOR SELECT
  TO authenticated
  USING (true);

